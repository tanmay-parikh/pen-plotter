  const ALIASES = { '{': '(', '}': ')', '`': "'", '‘': "'", '’': "'", '“': '"', '”': '"',
    '–': '-', '—': '-', '−': '-', '…': '.', ' ': ' ', '~': '-', '^': '*', '@': '#', '&': '+', '$': '#' };

  function expand(stroke) {
    const pts = [];
    const push = (x, y) => {
      const l = pts[pts.length - 1];
      if (!l || Math.abs(l[0] - x) > 1e-6 || Math.abs(l[1] - y) > 1e-6) pts.push([x, y]);
    };
    for (const it of stroke) {
      if (Array.isArray(it)) { push(it[0], it[1]); continue; }
      const [cx, cy, rx, ry, a0, a1] = it.arc;
      const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / 10));
      for (let i = 0; i <= n; i++) {
        const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
        push(cx + rx * Math.cos(a), cy + ry * Math.sin(a));
      }
    }
    return pts;
  }

  const compiled = {};
  for (const ch of Object.keys(RAW)) {
    const [w, ...strokes] = RAW[ch];
    compiled[ch] = { w, strokes: strokes.map(expand) };
  }

  function glyph(ch) {
    return compiled[ch] || compiled[ALIASES[ch]] || compiled['?'];
  }

  // Strip accents, unify quotes, expand tabs, drop CRs and other control characters.
  function normalize(text) {
    return String(text)
      .normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/\r/g, '').replace(/\t/g, '  ')
      .replace(/[^\S\n]/g, (c) => (c === ' ' ? c : ' '))
      .replace(/[\u0000-\u0009\u000B-\u001F]/g, '');
  }

  PW.Font = { CAP, XH, DESC, GAP, SPACE, glyph, normalize, supports: (ch) => !!compiled[ch] || !!compiled[ALIASES[ch]] };
